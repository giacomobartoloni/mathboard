import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const projectRoot = path.resolve(path.dirname(__filename), '..')
const sourcePath = path.join(projectRoot, 'public', 'icon-512x512.png')
const outputPath = path.join(projectRoot, 'public', 'favicon.svg')
const pngSignature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])

/**
 * Preserve the exact official icon. This is a self-contained SVG containing
 * raster PNG data, not a vector trace: it has no external font or image loads.
 */
export function svgForPng(source) {
  const png = Buffer.from(source)

  if (
    png.length < 26 ||
    !png.subarray(0, 8).equals(pngSignature) ||
    png.toString('ascii', 12, 16) !== 'IHDR'
  ) {
    throw new Error('public/icon-512x512.png is not a valid PNG header')
  }

  if (png.readUInt32BE(16) !== 512 || png.readUInt32BE(20) !== 512) {
    throw new Error('public/icon-512x512.png must be 512x512')
  }

  // 4 = grayscale + alpha, 6 = truecolor + alpha.
  if (![4, 6].includes(png[25])) {
    throw new Error('public/icon-512x512.png must have an alpha channel')
  }

  return `<!-- Generated by tools/generate-favicon-svg.mjs; do not edit. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <image width="512" height="512" href="data:image/png;base64,${png.toString('base64')}"/>
</svg>
`
}

async function main() {
  const png = await fs.readFile(sourcePath)
  await fs.writeFile(outputPath, svgForPng(png), 'utf8')
  console.log('Generated public/favicon.svg from public/icon-512x512.png')
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main().catch((error) => {
    console.error('Favicon SVG generation failed:')
    console.error(error)
    process.exitCode = 1
  })
}
